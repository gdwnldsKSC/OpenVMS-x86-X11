use strict;
use warnings;

my ($source, $output) = @ARGV;
die "Usage: perl GENERATE_RULES.PL source-rules-directory output-directory\n"
    unless defined $source && defined $output && @ARGV == 2;

sub read_file {
    my ($name) = @_;
    open my $file, '<', $name or die "$name: $!\n";
    binmode $file;
    local $/;
    my $text = <$file>;
    close $file or die "$name: $!\n";
    return $text;
}

sub write_file {
    my ($name, $text) = @_;
    open my $file, '>', $name or die "$name: $!\n";
    binmode $file;
    print {$file} $text or die "$name: $!\n";
    close $file or die "$name: $!\n";
}

# Match rules/bin/ml*_s.sh for the generated default compatibility fragments.
my @layouts = map { [split ' '] }
    split /\r?\n/, read_file("$source/compat/layoutsMapping.lst");
my @variants = map { [split ' '] }
    split /\r?\n/, read_file("$source/compat/variantsMapping.lst");
my %generated;
for my $group (0 .. 4) {
    my $suffix = $group ? $group : '';
    my $part = '';
    for my $row (@layouts) {
        my ($old, $new) = @$row;
        my $variant = index($new, '(') < 0 && $group ? "%(v[$group])" : '';
        $part .= $group < 2
            ? "  *\t\t$old\t\t\t=\tpc+$new$variant\n"
            : "  *\t\t$old\t\t=\t+$new$variant:$group\n";
    }
    for my $row (@variants) {
        my ($old, $oldvariant, $new, $newvariant) = @$row;
        $part .= $group < 2
            ? "  *\t\t$old($oldvariant)\t\t\t=\tpc+$new($newvariant)\n"
            : "  *\t\t$old($oldvariant)\t=\t+$new($newvariant):$group\n";
    }
    $generated{"compat/base.ml${suffix}_s.part"} = $part;
    $part = '';
    for my $row (@variants) {
        my ($old, $oldvariant, $new, $newvariant) = @$row;
        $part .= $group < 2
            ? "  *\t\t$old\t\t$oldvariant\t\t=\tpc+$new($newvariant)\n"
            : "  *\t\t$old\t\t$oldvariant\t=\t+$new($newvariant):$group\n";
    }
    $generated{"compat/base.ml${suffix}v${suffix}_s.part"} = $part;
}

# Match merge.sh using the default USE_COMPAT_RULES part lists from Makefile.am.
my $makefile = read_file("$source/Makefile.am");
$makefile =~ s/\\\r?\n/ /g;
my ($compat) = $makefile =~ /^if USE_COMPAT_RULES\s*\n(.*?)^else\s*$/ms;
die "Cannot find upstream compatibility rule lists\n" unless defined $compat;
for my $rules (qw(base evdev)) {
    my ($parts) = $compat =~ /^${rules}_parts\s*=\s*([^\r\n]+)/m;
    die "Cannot find upstream $rules parts\n" unless defined $parts;
    my @headers = split /\r?\n/, read_file("$source/HDR");
    my $text = "// DO NOT EDIT THIS FILE - IT WAS AUTOGENERATED BY merge.sh FROM rules/*.part\n";
    for my $part (split /\s+/, $parts) {
        if ($part eq 'HDR') {
            die "Too few upstream rule headers\n" unless @headers;
            $text .= "\n" . shift(@headers) . "\n";
        } elsif (exists $generated{$part}) {
            $text .= $generated{$part};
        } else {
            $text .= read_file("$source/$part");
        }
    }
    write_file("$output/$rules", $text);
}

# INTLTOOL_XML_NOMERGE_RULE removes the translation markers, without catalogs.
for my $name (qw(base.xml evdev.xml base.extras.xml evdev.extras.xml)) {
    my $xml = read_file("$source/$name.in");
    $xml =~ s{<(/?)_([A-Za-z][\w:.-]*)(?=[\s/>])}{<$1$2}g;
    write_file("$output/$name", $xml);
}

# Use the unmodified upstream converter for the old-format rules lists.
for my $rules (qw(base evdev)) {
    local *ARGV;
    local @ARGV = ("$output/$rules.xml");
    local *STDOUT;
    open STDOUT, '>', "$output/$rules.lst" or die "$output/$rules.lst: $!\n";
    binmode STDOUT;
    my $script = "$source/xml2lst.pl";
    $script = "./$script" unless $script =~ m{^(?:[/.]|[A-Za-z]:|[^/]+\[)};
    my $converted = do $script;
    die "$script: $@" if $@;
    die "$script: $!\n" unless defined $converted;
    close STDOUT or die "$output/$rules.lst: $!\n";
}
